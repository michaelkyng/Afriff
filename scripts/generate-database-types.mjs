import { spawnSync } from 'node:child_process'
import { renameSync, rmSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const destination = new URL('../packages/supabase/src/database.types.ts', import.meta.url)
const temporary = new URL(`${destination.href}.tmp`)

// Run only against the local stack. Keep the checked-in file intact on failure.
const result = spawnSync('supabase', ['gen', 'types', 'typescript', '--local', '--schema', 'public'], {
  cwd: root,
  encoding: 'utf8',
  stdio: ['ignore', 'pipe', 'inherit'],
  maxBuffer: 10 * 1024 * 1024,
})

if (result.error || result.status !== 0 || !result.stdout?.includes('export type Database')) {
  console.error(result.error?.message ?? 'Database type generation failed. Start the local Supabase stack first.')
  process.exit(1)
}

try {
  writeFileSync(temporary, '// Generated by bun run db:types. Do not edit manually.\n' + result.stdout)
  renameSync(temporary, destination)
} finally {
  rmSync(temporary, { force: true })
}

console.log('Updated packages/supabase/src/database.types.ts')
